export const locale: Locale = (globalThis.navigator?.language ?? '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
const messages: Record<Locale, Record<MessageKey, string>> = { en, fr };

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

