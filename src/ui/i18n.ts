export function translateError(reason: unknown, fallback = 'Something went wrong.'): string {
  const message = reason instanceof Error ? reason.message : typeof reason === 'string' ? reason : fallback;
  return locale === 'fr' ? errorsFr[message] ?? message : message;
}

